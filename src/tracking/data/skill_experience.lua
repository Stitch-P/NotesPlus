local Experience = {}

local function thresholds(skill)
    return skill == "INVENTION" and invention or standard
end

function Experience.MaxLevel(skill)
    return #thresholds(skill)
end

function Experience.Level(skill, xp)
    if type(xp) ~= "number" or xp ~= xp or xp < 0 or xp == math.huge then return nil end
    local levels = thresholds(skill)
    local low, high = 1, #levels
    while low < high do
        local middle = math.floor((low + high + 1) / 2)
        if xp >= levels[middle] then low = middle
        else high = middle - 1 end
    end
    return low
end

return Experience
