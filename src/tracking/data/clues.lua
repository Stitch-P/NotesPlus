for _, group in ipairs(ITEM_GROUPS) do
    if group.name ~= GROUP_OTHER then GROUP_ORDER[#GROUP_ORDER + 1] = group.name end
end
GROUP_ORDER[#GROUP_ORDER + 1] = GROUP_OTHER

