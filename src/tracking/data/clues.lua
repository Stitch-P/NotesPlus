local function itemGroup(name)
    if THIRD_AGE[name] then return "Second & Third age" end
    for _, group in ipairs(ITEM_GROUPS) do
        for _, fragment in ipairs(group.any) do
            if name:find(fragment, 1, true) then return group.name end
        end
    end
    return GROUP_OTHER
end

-- Order the sections appear in the Section dropdown.
